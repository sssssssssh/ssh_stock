def _equal(actual, expected):
    require(type(actual) is type(expected), "W04A_FIELD_TYPE")
    if type(expected) is dict:
        require(set(actual) == set(expected), "W04A_FIELDS")
        for key in expected:
            _equal(actual[key], expected[key])
    elif type(expected) is list:
        require(len(actual) == len(expected), "W04A_FIELDS")
        for left, right in zip(actual, expected, strict=True):
            _equal(left, right)
    else:
        require(actual == expected, "W04A_FIELD_VALUE")


