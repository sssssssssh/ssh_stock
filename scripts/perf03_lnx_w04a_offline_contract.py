    tables = value["tables"]
    expected_plan = plan_fingerprint(contract_definition() if plan is None else plan)
    require(value["plan_sha256"] == expected_plan, "W04A_SNAPSHOT_PLAN")
    require(type(tables) is dict and set(tables) == set(INPUT_SCHEMA), "W04A_TABLES")
    normalized, total = {}, 0
    for table, spec in INPUT_SCHEMA.items():
        rows = tables[table]
        require(type(rows) is list, "W04A_ROWS")
        total += len(rows)
        require(total <= MAX_ROWS, "W04A_ROWS")
        seen, ordered = set(), []
        for row in rows:
            require(type(row) is dict and set(row) == set(spec["columns"]), "W04A_COLUMNS")
            clean = {column: _cell(row[column], rule) for column, rule in spec["columns"].items()}
            key = canonical([clean[k] for k in spec["primary_key"]])
            require(key not in seen, "W04A_DUPLICATE_PK")
            seen.add(key)
            ordered.append((key, clean))
        normalized[table] = [row for _, row in sorted(ordered, key=lambda pair: pair[0])]
    return digest(
        {
            "schema": SNAPSHOT_SCHEMA,
            "evidence_kind": "SYNTHETIC_ONLY",
            "plan_sha256": expected_plan,
            "tables": normalized,
        }
    )


